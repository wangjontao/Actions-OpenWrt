#!/bin/sh
set -eu
[ "$(id -u)" = 0 ] || { echo 'Run as root'; exit 1; }
[ -x /usr/bin/juliang-fastacl-runtime ] || { echo 'FastACL runtime is required'; exit 1; }
case "$(uci -q get juliang_fastacl.main.version)" in 2.4.2|2.4.3) :;; *) echo 'FastACL 2.4.2 or 2.4.3 is required'; exit 1;; esac
command -v lua >/dev/null
[ ! -d /tmp/juliang-fastacl-runtime.lock ] && [ ! -d /tmp/juliang-fastacl-wifi.lock ] || { echo 'Another FastACL operation is running'; exit 1; }
TASK=$(mktemp -d /tmp/fastacl-batch-install.XXXXXX)
trap 'rm -rf "$TASK"' EXIT
umask 077
sed -n '/^__PAYLOAD__$/,$p' "$0" | sed '1d' | base64 -d > "$TASK/payload.tar.gz"
[ "$(sha256sum "$TASK/payload.tar.gz" | awk '{print $1}')" = 'afe0c9a055cd317b28fdd840924299d3d0f10f462db7f03c7519cefff3f3731b' ] || { echo 'Payload checksum failed'; exit 1; }
mkdir "$TASK/root"
tar -xzf "$TASK/payload.tar.gz" -C "$TASK/root"
find "$TASK/root" -name '*.lua' | while IFS= read -r path; do JFA_CHECK_PATH="$path" lua -e 'assert(loadfile(os.getenv("JFA_CHECK_PATH")))'; done
sh -n "$TASK/root/usr/bin/juliang-fastacl-guard"
[ "${1:-}" != --check ] || { echo 'FastACL batch WiFi preflight passed'; exit 0; }
BACKUP="/etc/juliang-fastacl/batch-install-$(date +%Y%m%d-%H%M%S)-$$"
mkdir -p "$BACKUP/root/etc/config"
cp -p /etc/config/juliang_fastacl "$BACKUP/root/etc/config/juliang_fastacl"
find "$TASK/root" -type f | while IFS= read -r path; do
    rel="${path#"$TASK/root/"}"
    if [ -e "/$rel" ]; then
        mkdir -p "$BACKUP/root/$(dirname "$rel")"
        cp -p "/$rel" "$BACKUP/root/$rel"
    else printf '%s\n' "$rel" >> "$BACKUP/new-files"; fi
    mkdir -p "/$(dirname "$rel")"
    cp -p "$path" "/$rel"
done
cat > "$BACKUP/rollback.sh" <<'ROLLBACK'
#!/bin/sh
set -eu
BASE=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
cp -a "$BASE/root/." /
if [ -s "$BASE/new-files" ]; then while IFS= read -r rel; do rm -f "/$rel"; done < "$BASE/new-files"; fi
rm -f /tmp/luci-indexcache /tmp/luci-indexcache.*
rm -rf /tmp/luci-modulecache /tmp/luci-templatecache
printf 'Batch WiFi files restored\n'
ROLLBACK
chmod 0700 "$BACKUP/rollback.sh"
uci set juliang_fastacl.main.version='2.4.3'
uci commit juliang_fastacl
rm -f /tmp/luci-indexcache /tmp/luci-indexcache.*
rm -rf /tmp/luci-modulecache /tmp/luci-templatecache
printf 'Installed FastACL 2.4.3 stable. Refresh FastACL console. Backup: %s\n' "$BACKUP"
exit 0
